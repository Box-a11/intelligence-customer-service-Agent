"""知识库分库分索引路由器：按关键词把查询路由到若干子索引（文档分片）。

每个分片对应一份知识文档（以 source 名标识），检索时先用 `route(query)` 定位相关分片，
只在命中的分片上召回，缩小检索范围、降低无关文档噪声。

设计为确定性、无外部依赖、可离线测试；命中关键词越多越相关。返回 `[]` 表示无任何命中，
由调用方（Retriever）决定回退全量检索。
"""
from __future__ import annotations

from typing import Dict, List, Optional, Tuple

# 每个分片（文档 source 名）的路由关键词；命中越多越相关。
SHARD_KEYWORDS: Dict[str, Tuple[str, ...]] = {
    "01-产品介绍": ("产品", "正品", "假一", "平台", "服务承诺", "客户类型", "商家", "自营"),
    "02-配送与物流": ("物流", "配送", "运费", "包邮", "偏远", "签收", "发货", "收货", "快递", "时效", "跟踪"),
    "03-退换货政策": ("退货", "换货", "退换", "七天无理由", "无理由", "质量问题", "质保"),
    "04-退款说明": ("退款", "到账", "极速退款", "部分退款", "退款进度", "退款路径"),
    "05-发票说明": ("发票", "开票", "电子发票", "抬头", "税号", "补开", "开票时间"),
    "06-会员与积分": ("会员", "积分", "权益", "等级", "开通", "降级"),
    "07-支付与安全": ("支付", "分期", "银行卡", "微信", "支付宝", "安全", "密码", "重复扣款", "账户", "扣款"),
    "08-常见故障与排查": ("闪退", "卡顿", "登录", "打不开", "故障", "异常", "冻结", "无法下单", "不更新"),
    "09-隐私政策": ("隐私", "数据", "注销", "授权", "未成年人", "收集", "个人信息"),
    "10-投诉与售后渠道": ("投诉", "举报", "差评", "售后渠道", "升级处理", "监管", "索赔"),
    "11-大促与优惠活动": ("优惠券", "大促", "活动", "618", "双11", "折扣", "满减", "新人", "价保", "叠加"),
    "12-客服联系方式": ("客服", "热线", "电话", "人工", "联系方式", "在线客服", "邮件"),
}


class Router:
    """关键词路由器：把查询映射到相关分片（文档）列表，按命中关键词数降序。"""

    def __init__(
        self,
        keywords: Optional[Dict[str, Tuple[str, ...]]] = None,
        top_n: int = 3,
    ):
        self.keywords = keywords or SHARD_KEYWORDS
        self.top_n = top_n

    def route(self, query: str) -> List[str]:
        """返回相关分片名列表（命中数降序，最多 top_n 个）；无命中返回空列表。"""
        ranked: List[Tuple[int, str]] = []
        for shard, kws in self.keywords.items():
            hits = sum(1 for k in kws if k in query)
            if hits:
                ranked.append((hits, shard))
        if not ranked:
            return []
        # 命中数降序；同命中数按分片名稳定排序，保证确定性
        ranked.sort(key=lambda x: (-x[0], x[1]))
        return [shard for _, shard in ranked[: self.top_n]]
